<?php declare(strict_types=1);

use App\Components\Blog\BlogFormComponent;
use App\Utils\CSSRenderer;

/** @var BlogFormComponent $data */
/** @var string $baseClass */

$formId = $data->formId;
$post = $data->post;
$permalink = $data->permalink;
$schedule = $data->schedule;

?>

<blog-form-component role="form">
    <form id="<?= $formId ?>" autocomplete="off">
        <input id="<?= "{$formId}__id" ?>"
            type="hidden"
            name="id"
            value="<?= $post?->id ?? 0 ?>">
    </form>

    <label for="<?= "{$formId}__title" ?>">
        Title:
        <input id="<?= "{$formId}__title" ?>"
            type="text"
            form="<?= $formId ?>"
            name="title"
            placeholder="Title"
            minlength="<?= INPUT_LENGTH['page_title']['min'] ?>"
            maxlength="<?= INPUT_LENGTH['page_title']['max'] ?>"
            pattern="<?= REGEX_HTML['default_text'] ?>"
            value="<?= $post?->title ?>"
            full-width
            required
            >
    </label>

    <blog-form-permalink>
        <?php if ($post?->publishedOn): ?>
            <?= $permalink ?>
            <input id="<?= "{$formId}__is-published" ?>"
                type="hidden"
                form="<?= $formId ?>"
                name="isPublished"
                value="<?= $permalink ?>">
        <?php else: ?>
            <span><?= $permalink->prefix ?></span>
            <span id="<?= "{$formId}__permadate" ?>">
                <?= $permalink->date ?>
            </span>
            <span>/</span>
            <input id="<?= "{$formId}__permatitle" ?>"
                type="text"
                form="<?= $formId ?>"
                name="permatitle"
                placeholder="Permalinks are automatically generated by default"
                pattern="<?= REGEX_HTML['permalink_title'] ?>"
                aria-label="Customizable part of the post's URL (i.e. address)"
                value="<?= $permalink->title ?>">
            <button id="<?= "{$formId}__reset-permalink" ?>"
                title="Restore default permalink"
                aria-label="Restore default permalink"
                >
                <svg width="1em" height="1em">
                    <use xlink:href="#svg-restore-setting" href="#svg-restore-setting"></use>
                </svg>
            </button>
        <?php endif ?>
    </blog-form-permalink>

    <!-- Text Editor -->

    <input id="<?= "{$formId}__content-short" ?>"
        type="hidden"
        form="<?= $formId ?>"
        name="contentShort"
        value="">
    <input id="<?= "{$formId}__content-rest" ?>"
        type="hidden"
        form="<?= $formId ?>"
        name="contentRest"
        value="">

    <label for="<?= "{$formId}__description" ?>">
        Description:
        <input id="<?= "{$formId}__description" ?>" full-width
            type="text"
            form="<?= $formId ?>"
            name="description"
            placeholder="A short description of the contents, for search engine previews, etc."
            minlength="<?= INPUT_LENGTH['page_description']['min'] ?>"
            maxlength="<?= INPUT_LENGTH['page_description']['max'] ?>"
            pattern="<?= REGEX_HTML['default_text'] ?>"
            value="<?= $post?->description ?>"
            required>
    </label>

    <label for="<?= "{$formId}__mastolink" ?>">
        Social Link:
        <input id="<?= "{$formId}__mastolink" ?>" full-width
            type="url"
            form="<?= $formId ?>"
            name="mastolink"
            placeholder="Social media link connected to this post"
            value="<?= $post?->mastolink ?>">
    </label>

    <blog-form-options class="flex-row gap-m justify-between">
        <options-group class="flex-row gap-m">
            <label for="<?= "{$formId}__toggle-pinned"?>">
                <input id="<?= "{$formId}__toggle-pinned" ?>"
                    type="checkbox"
                    form="<?= $formId ?>"
                    name="isPinned"
                    <?php if ($post?->isPinned): ?>
                        checked
                    <?php endif ?>
                    >
                Pinned
            </label>
            <?php if ($post?->publishedOn): ?>
                <label for="<?= "{$formId}__toggle-hidden" ?>">
                    <input id="<?= "{$formId}__toggle-hidden" ?>"
                        type="checkbox"
                        form="<?= $formId ?>"
                        name="isHidden"
                        <?php if ($post->isHidden): ?>
                            checked
                        <?php endif ?>
                        >
                    Hidden
                </label>
            <?php endif ?>
        </options-group>
        <options-group class="flex-row gap-m">
            <?php if (!$post?->publishedOn): ?>
                <input id="<?= "{$formId}__scheduled-date" ?>"
                    type="date"
                    form="<?= $formId ?>"
                    name="scheduledDate"
                    value="<?= $schedule?->publishOn->format('Y-m-d') ?>"
                    required
                    <?php if ($schedule): ?>
                        disabled
                        hidden
                    <?php endif ?>
                    >
                <input id="<?= "{$formId}__scheduled-time" ?>"
                    <?php if ($schedule): ?>
                        disabled
                        hidden
                    <?php endif ?>
                    type="time"
                    form="<?= $formId ?>"
                    name="scheduledTime"
                    step="60"
                    value="<?= $schedule?->publishOn->format('H:i') ?>"
                    required>
                <label for="<?= "{$formId}__toggle-schedule" ?>">
                    <input id="<?= "{$formId}__toggle-schedule" ?>"
                        type="checkbox"
                        form="<?= $formId ?>"
                        name="isScheduled"
                        <?php if ($schedule): ?>
                            checked
                        <?php endif ?>
                        >
                    Schedule
                </label>
            <?php endif ?>
        </options-group>
    </blog-form-options>
</blog-form-component>

<?php CSSRenderer::add($baseClass, <<<CSS
    .{$baseClass} {

    }
CSS) ?>
